/**
 * The machinery two photo scripts share: reading the key, calling the model, shrinking the file,
 * and rewriting the manifest the app reads.
 *
 * It lives here rather than being copied because every line of it was paid for once already —
 * the redaction exists because OpenAI quotes your key back at you in a 401, the resize because
 * 1024² images put megabytes nobody sees into the bundle, and the manifest-from-directory
 * because Metro resolves require() at build time and a missing file fails the whole bundle.
 */
import { Buffer } from 'node:buffer';
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The API's smallest square. The bundle keeps 768 — twice what the largest card shows at 3×. */
export const API_SIZE = '1024x1024';
const BUNDLE_SIZE = 768;
const JPEG_QUALITY = 85;

// Output tokens at $40/M: high 4160, medium 1056, low 272 for a 1024² square. Measured against
// gpt-image-1 and kept as an order of magnitude: the figure a script prints before a batch is
// there to make you stop and think, not to reconcile a bill.
export const CENTS_PER_IMAGE = { high: 16.6, medium: 4.2, low: 1.1 };

// gpt-image-1 was shut down on 2026-10-23; gpt-image-2 is its successor and carries no end date.
// IMAGE_MODEL overrides it — the 2.5 variants also exist, and are worth an --only comparison
// before a full regeneration rather than a blind switch.
export const MODEL = process.env.IMAGE_MODEL ?? 'gpt-image-2';

function env(name) {
  if (process.env[name]) return process.env[name];
  try {
    const line = readFileSync(join(ROOT, '.env'), 'utf8')
      .split('\n')
      .find((l) => l.startsWith(`${name}=`));
    return line?.slice(name.length + 1).trim();
  } catch {
    return undefined;
  }
}

export function key() {
  const value = env('OPENAI_API_KEY');
  if (!value) {
    console.error('OPENAI_API_KEY is not set. Put it in .env or pass it on the command line.');
    process.exit(1);
  }
  return value;
}

/** OpenAI quotes the key it was given back at you in a 401. Never print one. */
export function redactKeys(text) {
  return text.replace(/sk-[\w-]+/g, 'sk-…');
}

export async function generate(promptText, quality) {
  const res = await fetch('https://api.openai.com/v1/images/generations', {
    method: 'POST',
    headers: { Authorization: `Bearer ${key()}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: MODEL,
      prompt: promptText,
      n: 1,
      size: API_SIZE,
      quality,
      output_format: 'jpeg',
      // Close to lossless out of the model; the one lossy step is the resize below.
      output_compression: 95,
    }),
  });
  if (!res.ok) throw new Error(`OpenAI ${res.status}: ${redactKeys((await res.text()).slice(0, 300))}`);
  const body = await res.json();
  const b64 = body.data?.[0]?.b64_json;
  if (!b64) throw new Error(`no image in the response: ${JSON.stringify(body).slice(0, 300)}`);
  return Buffer.from(b64, 'base64');
}

/** 1024² down to 768², in place. sips ships with macOS, which beats adding an image library. */
export function resize(path) {
  execFileSync('sips', ['-Z', String(BUNDLE_SIZE), '-s', 'formatOptions', String(JPEG_QUALITY), path], {
    stdio: 'ignore',
  });
}

/**
 * Rewrites the module the app reads, listing only the photographs that are on disk.
 *
 * Generating the list from the directory rather than from the catalogue is what lets the app
 * build and run at seven photographs exactly as it will at fifty-six: whatever has no file falls
 * back to the picture it used before any of this existed.
 */
export function writeManifest({ dir, out, constName, assetPath, keyedBy }) {
  const slugs = readdirSync(dir)
    .filter((file) => file.endsWith('.jpg'))
    .map((file) => file.slice(0, -4))
    .sort();
  writeFileSync(
    join(ROOT, out),
    [
      "import type { ImageSourcePropType } from 'react-native';",
      '',
      `// Generated by ${keyedBy.script} — do not edit by hand.`,
      `// Keyed by ${keyedBy.by}.`,
      `export const ${constName}: Record<string, ImageSourcePropType> = {`,
      ...slugs.map((slug) => `  '${slug}': require('${assetPath}/${slug}.jpg'),`),
      '};',
      '',
    ].join('\n'),
  );
  console.log(`${out}: ${slugs.length} photographs`);
  return slugs.length;
}
